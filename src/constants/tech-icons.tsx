export function TechLogo({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Icon = TECH_ICONS[name];
  if (!Icon) {
    return (
      <span
        className={cn(
          "flex size-10 shrink-0 items-center justify-center rounded-lg border border-border bg-muted/50 text-xs font-medium text-muted-foreground",
          className,
        )}
        aria-hidden
      >
        {name.slice(0, 2)}
      </span>
    );
  }
  return <Icon className={className} color={TECH_COLORS[name]} aria-hidden />;
}
